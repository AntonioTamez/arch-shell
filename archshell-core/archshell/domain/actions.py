"""The closed action set `archshell/action/v1` as immutable data.

Pure: no IO, clock, randomness, or environment (AD-4). Ids and nonces are
generated by an adapter and passed in.
"""

from __future__ import annotations

from dataclasses import dataclass, fields
from typing import Any, ClassVar

ACTION_SCHEMA = "archshell/action/v1"

# Question text the host shows verbatim (AD-2): a short header and 2-4 labels.
HEADER_MAX_LENGTH = 12
OPTIONS_MIN = 2
OPTIONS_MAX = 4

Message = dict[str, Any]


class ActionError(ValueError):
    """A serialized action does not describe a valid `archshell/action/v1` action."""


@dataclass(frozen=True)
class _Action:
    type: ClassVar[str]
    terminal: ClassVar[bool] = False
    requires_human: ClassVar[bool] = False

    feature: str
    action_id: str
    revision: int

    def to_message(self) -> Message:
        message: Message = {"schema": ACTION_SCHEMA, "type": self.type}
        for field in fields(self):
            value = getattr(self, field.name)
            message[field.name] = list(value) if isinstance(value, tuple) else value
        return message


@dataclass(frozen=True)
class LlmTask(_Action):
    """A model task. The prompt is not carried inline: `prompt_file` is a POSIX
    path, relative to the project root, of a file the engine wrote holding the
    prompt, line endings normalized to LF, UTF-8 without BOM (AD-3)."""

    type: ClassVar[str] = "llm_task"
    prompt_file: str


@dataclass(frozen=True)
class Ask(_Action):
    type: ClassVar[str] = "ask"
    requires_human: ClassVar[bool] = True
    question: str
    header: str
    options: tuple[str, ...]
    nonce: str


@dataclass(frozen=True)
class Confirm(_Action):
    """A yes/no confirmation. The first option confirms; any other declines."""

    type: ClassVar[str] = "confirm"
    requires_human: ClassVar[bool] = True
    question: str
    header: str
    options: tuple[str, ...]
    nonce: str


@dataclass(frozen=True)
class InstructAgent(_Action):
    type: ClassVar[str] = "instruct_agent"
    instruction: str


@dataclass(frozen=True)
class Report(_Action):
    type: ClassVar[str] = "report"
    terminal: ClassVar[bool] = True
    summary: str


@dataclass(frozen=True)
class Done(_Action):
    type: ClassVar[str] = "done"
    terminal: ClassVar[bool] = True
    summary: str


Action = LlmTask | Ask | Confirm | InstructAgent | Report | Done

ACTION_TYPES: dict[str, type[_Action]] = {
    cls.type: cls for cls in (LlmTask, Ask, Confirm, InstructAgent, Report, Done)
}


def action_from_message(message: Any) -> Action:
    """Rebuild an action from its `to_message()` form; raise `ActionError` if invalid."""
    if not isinstance(message, dict):
        raise ActionError("action must be an object")
    if message.get("schema") != ACTION_SCHEMA:
        raise ActionError(f"action schema must be {ACTION_SCHEMA}")
    cls = ACTION_TYPES.get(message.get("type"))  # type: ignore[arg-type]
    if cls is None:
        raise ActionError(f"unknown action type: {message.get('type')!r}")
    names = [field.name for field in fields(cls)]
    if set(message) != {"schema", "type", *names}:
        raise ActionError(f"{cls.type} fields must be exactly {sorted(names)}")
    values: dict[str, Any] = {}
    for name in names:
        value = message[name]
        if name == "revision":
            if not isinstance(value, int) or isinstance(value, bool) or value < 1:
                raise ActionError("revision must be a positive integer")
        elif name == "options":
            if (
                not isinstance(value, (list, tuple))
                or not OPTIONS_MIN <= len(value) <= OPTIONS_MAX
                or not all(isinstance(label, str) and label.strip() for label in value)
                or len(set(value)) != len(value)
            ):
                raise ActionError(
                    f"options must be {OPTIONS_MIN}-{OPTIONS_MAX} unique non-blank strings"
                )
            value = tuple(value)
        elif not isinstance(value, str):
            raise ActionError(f"{name} must be a string")
        elif name == "header" and (
            not value.strip() or len(value) > HEADER_MAX_LENGTH
        ):
            raise ActionError(f"header must be non-blank, at most {HEADER_MAX_LENGTH} characters")
        values[name] = value
    return cls(**values)  # type: ignore[return-value]
